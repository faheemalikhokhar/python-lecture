# comparison operators
num1 = 15
num2 = 20

# equality (==)  output is boolean
equal = num1 == num2  # False
# print("Is num1 equal to num2?", equal)
# print(f"equal: {equal}")

# not equal (!=) output is boolean
not_equal = (num1 != num2)  # True
# print("Is num1 not equal to num2?", not_equal)
# print(f"not_equal: {not_equal}")
# print(f"not_equal ({num1} != {num2}): {not_equal}")

# greater than (>) output is boolean
greater_than = (num1 > num2)  # False
# print("Is num1 greater than num2?", greater_than)
# print(f"greater_than: {greater_than}")
# print(f"greater_than ({num1} > {num2}): {greater_than}")

# less than (<) output is boolean
less_than = (num1 < num2)  # True
# print("Is num1 less than num2?", less_than)
# print(f"less_than: {less_than}")
# print(f"less_than ({num1} < {num2}): {less_than}")

# greater than or equal to (>=) output is boolean
greater_equal = (num1 >= num2)  # False
# print("Is num1 greater than or equal to num2?", greater_equal)
# print(f"greater_equal: {greater_equal}")
# print(f"greater_equal ({num1} >= {num2}): {greater_equal}")

# less than or equal to (<=) output is boolean
less_equal = (num1 <= num2)  # True
